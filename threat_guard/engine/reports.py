"""Export ThreatGuard reports as JSON, CSV, or HTML."""
from __future__ import annotations
import csv
import html
import io
import json
from pathlib import Path


def _collect_rows(report: dict) -> list[dict]:
    """Normalize findings / audit_checks / checks into a flat row list."""
    for key in ("findings", "audit_checks", "checks"):
        items = report.get(key)
        if isinstance(items, list):
            return items
    return []


def to_json(report: dict) -> str:
    return json.dumps(report, indent=2, ensure_ascii=False)


def to_csv(report: dict) -> str:
    rows = _collect_rows(report)
    fields = ["severity", "engine", "check", "status", "title",
              "details", "path", "sha256", "line_number", "pattern"]
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=fields, extrasaction="ignore")
    writer.writeheader()
    for row in rows:
        writer.writerow(row)
    return buf.getvalue()


_CSS = """
body{font-family:system-ui,sans-serif;background:#0f172a;color:#e2e8f0;margin:2rem}
h1{color:#10b981;margin-bottom:.25rem}
p.muted{color:#94a3b8}
table{width:100%;border-collapse:collapse;margin-top:1rem;font-size:.9rem}
th,td{text-align:left;padding:8px;border-bottom:1px solid #334155;vertical-align:top}
th{background:#1e293b}
tr:hover{background:#1e293b}
.sev-critical{color:#ef4444;font-weight:bold}
.sev-high{color:#f97316;font-weight:bold}
.sev-medium{color:#f59e0b}
.sev-warn{color:#f59e0b}
.sev-info{color:#38bdf8}
"""


def _severity_class(value: str) -> str:
    v = (value or "").lower()
    return f"sev-{v}" if v in {"critical", "high", "medium", "warn", "info"} else ""


def to_html(report: dict, title: str = "ThreatGuard Report") -> str:
    rows = _collect_rows(report)
    body_rows = []
    for row in rows:
        sev = str(row.get("severity") or row.get("status") or "")
        engine = str(row.get("engine") or row.get("check") or "")
        primary = str(row.get("title") or row.get("pattern") or row.get("details") or "")
        details = str(row.get("details") or "")
        path = str(row.get("path") or row.get("file") or "")
        body_rows.append(
            f"<tr>"
            f"<td class='{_severity_class(sev)}'>{html.escape(sev)}</td>"
            f"<td>{html.escape(engine)}</td>"
            f"<td>{html.escape(primary)}</td>"
            f"<td>{html.escape(details)[:400]}</td>"
            f"<td>{html.escape(path)}</td>"
            f"</tr>"
        )
    tbody = "\n".join(body_rows) or '<tr><td colspan="5">No findings.</td></tr>'
    return (
        "<!doctype html><html lang='en'><head><meta charset='utf-8'>"
        f"<title>{html.escape(title)}</title><style>{_CSS}</style></head><body>"
        f"<h1>{html.escape(title)}</h1>"
        "<p class='muted'>Generated by ThreatGuard. Findings are advisory and read-only.</p>"
        "<table><thead><tr>"
        "<th>Severity</th><th>Engine/Check</th><th>Title/Pattern</th>"
        "<th>Details</th><th>Path</th>"
        "</tr></thead><tbody>"
        f"{tbody}</tbody></table></body></html>"
    )


def write_report(report: dict, path: str | Path, fmt: str | None = None) -> Path:
    p = Path(path).expanduser()
    p.parent.mkdir(parents=True, exist_ok=True)
    fmt = (fmt or p.suffix.lstrip(".") or "json").lower()
    if fmt == "json":
        p.write_text(to_json(report), encoding="utf-8")
    elif fmt == "csv":
        p.write_text(to_csv(report), encoding="utf-8")
    elif fmt in {"html", "htm"}:
        p.write_text(to_html(report), encoding="utf-8")
    else:
        raise ValueError(f"Unsupported report format: {fmt!r}")
    return p